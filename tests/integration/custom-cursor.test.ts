  for (const outcome of ['resolve', 'reject'] as const) {
    test(`${mode}: Stop clears cursor assets before suspended PNG inflate can ${outcome} late`, async () => {
      const blocked = gate(), lateError = new Error('late cursor inflate failure')
      await withFixture(binary, String.raw`
child.cursor="a.cur";
function held(){child.cursor="waiting.cur";Debug.message("custom-cursor-tail");return child.cursor;}
`, {
        'a.cur': cur(255, 0, 0),
        'waiting.cur': cursorFile([{ width: 1, height: 1, payload: cursorPng(1, 1, [0, 255, 0, 128]) }]),
      }, async (f) => {
        const operation = observe(f.run('held'))
        await enteredGate(blocked.entered, operation)
        assert.equal(f.session.snapshot().cursorCacheEntries, 1)
        assert.equal(f.session.snapshot().cursorCacheBytes, loadedImageBytes)
        assert.equal(f.session.snapshot().cursorCachePending, 1)
        assert.deepEqual(f.definitions().map((event) => event.id), [2])
        // Stop must settle while the real inflater is still held; releasing it
        // first would hide a cancellation dependency on the late decoder.
        await f.session.stop()
        const stopped = await operation
        assert.equal(stopped.status, 'rejected')
        if (stopped.status === 'rejected') assert.match(String(stopped.error), /cancelled/i)
        assert.equal(f.session.snapshot().state, 'stopped')
        assert.equal(f.session.snapshot().cursorCacheEntries, 0)
        assert.equal(f.session.snapshot().cursorCacheBytes, 0)
        assert.equal(f.session.snapshot().cursorCachePending, 0)
        assert.equal(f.events.filter((event) => event.type === 'cursor-assets-clear').length, 1)
        blocked.release()
        await blocked.finished
        await nextTurn()
        await f.session.idle()
        assert.deepEqual(f.definitions().map((event) => event.id), [2])
        assert.equal(f.logs.includes('custom-cursor-tail'), false)
        assert.equal(f.session.snapshot().cursorCacheEntries, 0)
        assert.equal(f.session.snapshot().cursorCacheBytes, 0)
        assert.equal(f.session.snapshot().cursorCachePending, 0)
        const cleared = f.events.findIndex((event) => event.type === 'cursor-assets-clear')
        assert.equal(f.events.slice(cleared + 1).some((event) => event.type === 'cursor-asset'), false)
      }, {
        async inflateImage(bytes, expectedLength) {
          blocked.enter()
          try {
            await blocked.held
            if (outcome === 'reject') throw lateError
            return await inflateImage(bytes, expectedLength)
          } finally { blocked.finish() }
        },
      }, blocked.release)
    })
  }
