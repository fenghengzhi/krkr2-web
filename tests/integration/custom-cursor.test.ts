interface Fixture extends Awaited<ReturnType<typeof headless>> {
  windowId: number
  run(name: string): Promise<string>
  move(x?: number, y?: number, shift?: number): Promise<void>
  view(): InputView
  definitions(): Definition[]
}

// The operation functions themselves are in the source/compiled storage, not
// generated by evaluate. No test reads or mutates the Session's Layer maps.
async function withFixture(
  binary: boolean,
  body: string,
  files: Record<string, string | Uint8Array>,
  run: (fixture: Fixture) => Promise<void>,
  overrides: Partial<SessionDependencies> = {},
  release: () => void = () => {},
) {
  const f = await headless({ 'startup.tjs': '', 'custom-cursor.tjs': scene + body, ...files }, overrides)
  let failed = false, primary: unknown
  try {
    await f.session.start()
    if (binary) {
      await f.session.evaluate('Scripts.compileStorage("custom-cursor.tjs","savedata/custom-cursor.cjs",false,true,false)')
      await f.session.evaluate('Scripts.execStorage("savedata/custom-cursor.cjs")')
    } else await f.session.evaluate('Scripts.execStorage("custom-cursor.tjs")')
    await f.session.idle()
    const windowId = Number(await f.session.evaluate('win.__windowId'))
    await run({
      ...f, windowId,
      async run(name) {
        const result = await f.session.evaluate(`${name}()`)
        await f.session.idle()
        return result
      },
      async move(x = 20, y = 20, shift = 0) {
        await f.session.input({ type: 'move', windowId, x, y, shift, button: 0, clicks: 0 })
        await f.session.idle()
      },
      view() {
        for (let i = f.events.length - 1; i >= 0; i--) {
          const event = f.events[i]!
          if (event.type === 'window-input' && event.windowId === windowId) return event.input
        }
        throw new Error('Custom cursor fixture has no Window input view')
      },
      definitions: () => f.events.filter((event): event is Definition => event.type === 'cursor-asset'),
    })
  } catch (error) {
    failed = true
    primary = error
  }
  const cleanupErrors: unknown[] = []
  try { release() } catch (error) { cleanupErrors.push(error) }
  try { await f.session.stop() } catch (error) { cleanupErrors.push(error) }
  try {
    const snapshot = f.session.snapshot()
    assert.equal(snapshot.cursorCacheEntries, 0)
    assert.equal(snapshot.cursorCacheBytes, 0)
    assert.equal(snapshot.cursorCachePending, 0)
    assert.equal(snapshot.handles, 0)
    assert.equal(snapshot.bitmapBytes, 0)
    assert(Object.values(f.session.inspectOwnership()).every((value) => value === 0))
    assert.equal(f.events.filter((event) => event.type === 'cursor-assets-clear').length, 1)
  } catch (error) { cleanupErrors.push(error) }
  if (failed && cleanupErrors.length)
    throw new AggregateError([primary, ...cleanupErrors], 'Custom cursor operation and cleanup failed', { cause: primary })
  if (failed) throw primary
  if (cleanupErrors.length === 1) throw cleanupErrors[0]
  if (cleanupErrors.length) throw new AggregateError(cleanupErrors, 'Custom cursor cleanup failed')
}

function gate() {
  let enter!: () => void, release!: () => void, finish!: () => void
  const entered = new Promise<void>((resolve) => { enter = resolve }),
    held = new Promise<void>((resolve) => { release = resolve }),
    finished = new Promise<void>((resolve) => { finish = resolve })
  return { enter, release, finish, entered, held, finished }
}

function observe<T>(work: Promise<T>) {
  return work.then(
    (value) => ({ status: 'fulfilled' as const, value }),
    (error: unknown) => ({ status: 'rejected' as const, error }),
  )
}

async function enteredGate<T>(entered: Promise<void>, operation: ReturnType<typeof observe<T>>) {
  let timer: ReturnType<typeof setTimeout> | undefined
  try {
    await Promise.race([
      entered,
      operation.then((result) => {
        const cause = result.status === 'rejected' ? result.error : undefined
        throw new Error(`Cursor operation settled before PNG inflate: ${result.status}`, { cause })
      }),
      new Promise<never>((_, reject) => {
        timer = setTimeout(() => reject(new Error('Cursor operation did not enter PNG inflate')), 10000)
      }),
    ])
  } finally { clearTimeout(timer) }
}

